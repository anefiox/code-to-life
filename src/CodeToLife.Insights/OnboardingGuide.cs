using System.Text;

namespace CodeToLife.Insights;

/// <summary>A Markdown onboarding guide built from everything Code to Life knows about the solution, to read or commit.</summary>
public static class OnboardingGuide
{
    static string Cell(string? text) => (text ?? "").Replace("|", "\\|").ReplaceLineEndings(" ");
    static string Code(string text) => "`" + text.Replace('`', '\'') + "`";

    public static string Build(GraphIndex index, DateTimeOffset? date = null)
    {
        var graph = index.Graph;
        var explanations = Explanations.For(index);
        var md = new StringBuilder();
        void Line(string text = "") => md.Append(text).Append('\n');
        Line($"# Getting started with {graph.Name}");
        Line();
        Line($"_Generated by Code to Life on {(date ?? DateTimeOffset.UtcNow):yyyy-MM-dd}. Regenerate it after big changes._");
        Line();
        Line("## Projects");
        Line();
        foreach (var project in graph.Projects)
            Line($"- **{project.Name}** ({project.OutputKind switch { "exe" => "a program", "test" => "tests", _ => "a library" }}): {Code(ProjectFiles.Relative(graph.Root, project.Path))}");
        Line();

        var tools = Glossary.ForProject(graph);
        if (tools.Count > 0)
        {
            Line("## Tools it is built with");
            Line();
            foreach (var tool in tools) Line($"- **{tool.Term}** ({Code(tool.Package)}): {tool.Meaning}");
            Line();
        }
        var recipes = Recipes.For(index);
        if (recipes.FirstOrDefault(r => r.Id == "run") is { } run)
        {
            Line("## Run it");
            Line();
            foreach (var step in run.Steps) Line("- " + step.Text);
            Line();
        }
        Line("## How the code is organised");
        Line();
        foreach (var group in Folders.Groups(graph))
            Line($"- {Code((group.Dir.Length == 0 ? "(solution root)" : group.Dir) + "/")} · {group.Files.Count} file{(group.Files.Count == 1 ? "" : "s")}, " +
                $"{group.Types.Count} type{(group.Types.Count == 1 ? "" : "s")}{(Folders.Note(group.Dir) is { } note ? ": " + note : "")}");
        Line();

        var tour = Learning.StartTour(index);
        if (tour.Count > 0)
        {
            Line("## Start here");
            Line();
            Line("Read these in order. Each one leads to the next.");
            Line();
            for (var i = 0; i < tour.Count; i++)
            {
                var step = tour[i];
                Line($"{i + 1}. **{step.Name}**{(step.File is null ? "" : " in " + Code(step.File))}: {step.Reason}");
                if ((explanations.GetValueOrDefault(step.Id)?.Summary ?? explanations.GetValueOrDefault(step.TypeId)?.Summary) is { } summary)
                {
                    Line("   ");
                    Line("   " + summary.ReplaceLineEndings(" "));
                }
            }
            Line();
        }
        var pages = Learning.RouteFlows(index);
        if (pages.Routes.Count > 0)
        {
            Line("## Pages");
            Line();
            Line("| Method | Address | Handled by | View |");
            Line("| --- | --- | --- | --- |");
            foreach (var route in pages.Routes)
                Line($"| {Cell(route.Method == "*" ? "ANY" : route.Method)} | {Cell(route.Path)} | {Cell(index.Display(route.Handler) + (route.File is null ? "" : " (" + route.File + ")"))} | " +
                    $"{Cell(string.Join(", ", route.Templates.Select(t => t.File ?? t.Name)))} |");
            Line();
            if (pages.Before is not null) { Line(pages.Before); Line(); }
        }
        var settings = Settings.For(index);
        if (settings.Settings.Count > 0)
        {
            Line("## Settings");
            Line();
            Line("| Setting | Environment variable | Default | What it is for |");
            Line("| --- | --- | --- | --- |");
            foreach (var setting in settings.Settings)
                Line($"| {Cell(setting.Key)} | {Cell(setting.Env)} | {Cell(setting.Sensitive ? "(secret)" : setting.Default)} | {Cell(setting.Doc)} |");
            Line();
        }
        var howTo = recipes.Where(r => r.Id != "run").ToList();
        if (howTo.Count > 0)
        {
            Line("## How do I…");
            Line();
            foreach (var recipe in howTo)
            {
                Line("### " + recipe.Title);
                Line();
                Line(recipe.Summary);
                Line();
                for (var i = 0; i < recipe.Steps.Count; i++)
                {
                    var step = recipe.Steps[i];
                    Line($"{i + 1}. {step.Text}{(step.File is null ? "" : $" See {Code(step.File + ":" + step.Line)}.")}");
                }
                Line();
            }
        }
        var explained = graph.Types.Where(t => explanations.ContainsKey(t.Id)).OrderBy(t => t.Id, StringComparer.Ordinal).ToList();
        if (explained.Count > 0)
        {
            Line("## Classes explained");
            Line();
            foreach (var type in explained) Line($"- **{type.Name}**{(type.File is null ? "" : " (" + Code(ProjectFiles.Relative(graph.Root, type.File)) + ")")}: {explanations[type.Id].Summary.ReplaceLineEndings(" ")}");
            Line();
        }
        var history = GitHistory.For(graph);
        if (history.Available && history.Files.Count > 0)
        {
            Line("## Most changed files");
            Line();
            Line("Files that change often are where most work happens, and where a mistake is most likely.");
            Line();
            foreach (var file in history.Files.Take(10)) Line($"- {Code(file.File)}: {file.Commits} commit{(file.Commits == 1 ? "" : "s")}, last on {file.Last}");
            Line();
        }
        return md.ToString();
    }
}
